
// ARREDONDAMENTO
console.log(Math.round(4.5)); // 5   arredonda para o mais próximo
console.log(Math.floor(4.9)); // 4   arredonda para baixo
console.log(Math.ceil(4.1));  // 5   arredonda para cima
console.log(Math.trunc(4.9)); // 4   remove a parte decimal

// MÁXIMO E MÍNIMO
console.log(Math.max(3, 9, 5)); // 9
console.log(Math.min(3, 9, 5)); // 3

// POTÊNCIA E RAIZ
console.log(Math.pow(2, 3)); // 8
console.log(Math.sqrt(16));  // 4

// VALOR ABSOLUTO
console.log(Math.abs(-7)); // 7

// ALEATÓRIO
console.log(Math.random()); // número entre 0 e 1 (ex: 0.42)

// ALEATÓRIO INTEIRO ENTRE 1 E 10
console.log(Math.floor(Math.random() * 10) + 1);

// CONSTANTE
console.log(Math.PI); // 3.141592653589793